create extension if not exists pgcrypto;

create table if not exists public.tournament_settings (
  id integer primary key check (id = 1),
  registration_open boolean not null default true,
  updated_at timestamptz not null default now()
);

insert into public.tournament_settings (id, registration_open)
values (1, true)
on conflict (id) do nothing;

create table if not exists public.teams (
  id uuid primary key default gen_random_uuid(),
  team_number bigint generated by default as identity unique,
  team_name text not null check (char_length(team_name) between 2 and 32),
  captain_nick text not null check (char_length(captain_nick) between 1 and 24),
  captain_class text not null check (char_length(captain_class) between 1 and 12),
  player2_nick text not null check (char_length(player2_nick) between 1 and 24),
  player2_class text not null check (char_length(player2_class) between 1 and 12),
  player3_nick text not null check (char_length(player3_nick) between 1 and 24),
  player3_class text not null check (char_length(player3_class) between 1 and 12),
  reserve_nick text,
  reserve_class text,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  is_public boolean not null default false,
  submission_token uuid not null unique,
  created_at timestamptz not null default now(),
  check (
    (coalesce(reserve_nick, '') = '' and coalesce(reserve_class, '') = '')
    or
    (char_length(coalesce(reserve_nick, '')) between 1 and 24 and char_length(coalesce(reserve_class, '')) between 1 and 12)
  ),
  check (not is_public or status = 'approved')
);

create index if not exists teams_public_listing_idx
  on public.teams (team_number)
  where status = 'approved' and is_public = true;

create index if not exists teams_created_at_idx on public.teams (created_at desc);

-- Храним только SHA-256 хеш IP, не исходный адрес. Лимит: 3 заявки за 10 минут.
create table if not exists public.registration_rate_limits (
  ip_hash text primary key check (char_length(ip_hash) = 64),
  window_started_at timestamptz not null default now(),
  attempts integer not null default 0
);

create or replace function public.consume_registration_rate_limit(p_ip_hash text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  current_attempts integer;
begin
  insert into public.registration_rate_limits (ip_hash, window_started_at, attempts)
  values (p_ip_hash, now(), 1)
  on conflict (ip_hash) do update
    set attempts = case
      when public.registration_rate_limits.window_started_at < now() - interval '10 minutes' then 1
      else public.registration_rate_limits.attempts + 1
    end,
    window_started_at = case
      when public.registration_rate_limits.window_started_at < now() - interval '10 minutes' then now()
      else public.registration_rate_limits.window_started_at
    end
  returning attempts into current_attempts;

  return current_attempts <= 3;
end;
$$;

alter table public.tournament_settings enable row level security;
alter table public.teams enable row level security;
alter table public.registration_rate_limits enable row level security;

-- Удаляем возможные ранее созданные публичные политики с этими именами.
drop policy if exists "Public can read published teams" on public.teams;
drop policy if exists "Public can read tournament settings" on public.tournament_settings;

revoke all on public.teams from anon, authenticated;
revoke all on public.tournament_settings from anon, authenticated;
revoke all on public.registration_rate_limits from anon, authenticated;
revoke all on function public.consume_registration_rate_limit(text) from public, anon, authenticated;
grant execute on function public.consume_registration_rate_limit(text) to service_role;

